package com.redstonelogics.export;

import com.redstonelogics.analysis.BooleanAbstraction;
import com.redstonelogics.analysis.TruthTable;
import com.redstonelogics.graph.Netlist;
import com.redstonelogics.mapper.RedstoneLogicMapper;

import java.util.ArrayList;
import java.util.List;

public final class VerilogExporter {

    public static String render(RedstoneLogicMapper mapped, String moduleName) {
        Netlist netlist = mapped.netlist();
        BooleanAbstraction logic = mapped.logic();

        List<String> ins = new ArrayList<>();
        for (Netlist.Element e : netlist.inputs()) {
            ins.add(identifier(e.label));
        }
        List<String> outs = new ArrayList<>();
        for (Netlist.Element e : netlist.outputs()) {
            outs.add(identifier(e.label));
        }
        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by RedstoneLogics from ").append(netlist.dustNets().size())
          .append(" dust net(s) and ").append(netlist.elements().size())
          .append(" component(s).\n");
        sb.append("// Combinational only: repeater delay and any latch behaviour are\n");
        sb.append("// dropped by this export.\n\n");
        sb.append("module ").append(identifier(moduleName)).append(" (\n");
        for (String i : ins) {
            sb.append("    input  wire ").append(i).append(",\n");
        }
        for (int i = 0; i < outs.size(); i++) {
            sb.append("    output wire ").append(outs.get(i))
              .append(i == outs.size() - 1 ? "\n" : ",\n");
        }
        sb.append(");\n\n");

        for (Netlist.Element out : netlist.outputs()) {
            BooleanAbstraction.Fn fn = logic.function(out.id);
            String rhs;
            if (!fn.known()) {
                rhs = "1'bx  // function could not be determined";
            } else {
                List<String> names = new ArrayList<>();
                for (String n : logic.namesFor(fn)) {
                    names.add(identifier(n));
                }
                rhs = expression(fn.table(), names);
            }
            sb.append("    assign ").append(identifier(out.label))
              .append(" = ").append(rhs).append(";\n");
        }

        sb.append("\nendmodule\n");
        return sb.toString();
    }

    public static String expression(TruthTable table, List<String> names) {
        List<TruthTable.Cube> cubes = table.sop();
        if (cubes.isEmpty()) {
            return "1'b0";
        }
        List<String> terms = new ArrayList<>();
        for (TruthTable.Cube c : cubes) {
            List<String> literals = new ArrayList<>();
            for (int v = 0; v < table.vars; v++) {
                int bit = 1 << v;
                if ((c.mask() & bit) !=0) {
                    continue;
                }
                String name = v < names.size() ? names.get(v) : "v" + v;
                literals.add(((c.value() & bit) != 0) ? name : "~" + name);
            }
            if (literals.isEmpty()) {
                return "1'b1";
            }
            terms.add(literals.size() == 1
                    ? literals.get(0)
                    : "(" + String.join(" & ", literals) + ")");
        }
        return String.join(" | ", terms);
    }

    private static String identifier(String raw) {
        String s = raw.replaceAll("[^A-Za-z0-9_]", "_");
        return s.isEmpty() || Character.isDigit(s.charAt(0)) ? "n" + s : s;
    }

    private VerilogExporter() {
    }
}