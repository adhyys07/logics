package com.redstonelogics.export;

import com.redstonelogics.recognize.GateType;
import com.redstonelogics.recognize.LogicDiagram;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

public final class ArduinoExporter {

    private static final int FIRST_INPUT_PIN = 2;

    private ArduinoExporter() {
    }

    public static String render(LogicDiagram diagram, String title) {
        StringBuilder sb = new StringBuilder();
        Map<Integer, String> names = new LinkedHashMap<>();
        Map<Integer, Integer> pins = new LinkedHashMap<>();

        List<LogicDiagram.Gate> inputs = diagram.inputs();
        List<LogicDiagram.Gate> outputs = diagram.outputs();

        int pin = FIRST_INPUT_PIN;
        for (LogicDiagram.Gate g : inputs) {
            names.put(g.id, "in_" + identifier(g.label));
            pins.put(g.id, pin++);
        }
        for (LogicDiagram.Gate g : outputs) {
            names.put(g.id, "out_" + identifier(g.label));
            pins.put(g.id, pin++);
        }
        for (LogicDiagram.Gate g : diagram.gates()) {
            names.computeIfAbsent(g.id, id -> "n_" + identifier(g.label));
        }

        sb.append("// ").append(title).append('\n');
        sb.append("// Generated by RedstoneLogics from a scanned redstone circuit.\n");
        sb.append("// Inputs are wired to ground with INPUT_PULLUP, so a closed switch reads LOW\n");
        sb.append("// and is inverted back to true below.\n\n");

        for (LogicDiagram.Gate g : inputs) {
            sb.append(String.format(Locale.ROOT, "const uint8_t PIN_%s = %d;  // %s%n",
                    identifier(g.label).toUpperCase(Locale.ROOT), pins.get(g.id),
                    g.note == null ? "input" : g.note));
        }
        for (LogicDiagram.Gate g : outputs) {
            sb.append(String.format(Locale.ROOT, "const uint8_t PIN_%s = %d;%n",
                    identifier(g.label).toUpperCase(Locale.ROOT), pins.get(g.id)));
        }
        sb.append('\n');

        List<LogicDiagram.Gate> latches = new ArrayList<>();
        for (LogicDiagram.Gate g : diagram.gates()) {
            if (g.type == GateType.SR_LATCH || g.type == GateType.FEEDBACK) {
                latches.add(g);
                sb.append(String.format(Locale.ROOT, "bool %s_q = false;  // stored state%n",
                        names.get(g.id)));
            }
        }
        if (!latches.isEmpty()) {
            sb.append('\n');
        }

        sb.append("void setup() {\n");
        for (LogicDiagram.Gate g : inputs) {
            sb.append("  pinMode(PIN_").append(identifier(g.label).toUpperCase(Locale.ROOT))
              .append(", INPUT_PULLUP);\n");
        }
        for (LogicDiagram.Gate g : outputs) {
            sb.append("  pinMode(PIN_").append(identifier(g.label).toUpperCase(Locale.ROOT))
              .append(", OUTPUT);\n");
        }
        sb.append("}\n\nvoid loop() {\n");

        for (LogicDiagram.Gate g : inputs) {
            sb.append(String.format(Locale.ROOT, "  bool %s = (digitalRead(PIN_%s) == LOW);%n",
                    names.get(g.id), identifier(g.label).toUpperCase(Locale.ROOT)));
        }
        sb.append('\n');

        for (int id : diagram.topologicalOrder()) {
            LogicDiagram.Gate g = diagram.gate(id);
            switch (g.type) {
                case INPUT -> {
                }
                case CONST_0, CONST_1 -> sb.append(String.format(Locale.ROOT,
                        "  bool %s = %s;%n", names.get(id),
                        g.type == GateType.CONST_1 ? "true" : "false"));
                case SR_LATCH -> emitLatch(sb, diagram, g, names);
                case FEEDBACK -> {
                    sb.append("  // ").append(g.note).append('\n');
                    sb.append(String.format(Locale.ROOT,
                            "  bool %s = %s_q;  // review this by hand%n",
                            names.get(id), names.get(id)));
                }
                case OUTPUT -> {
                    String source = g.inputs.isEmpty() ? "false" : names.get(g.inputs.get(0).gate());
                    sb.append(String.format(Locale.ROOT, "  digitalWrite(PIN_%s, %s ? HIGH : LOW);%n",
                            identifier(g.label).toUpperCase(Locale.ROOT), source));
                }
                default -> {
                    if (g.delayTicks > 0) {
                        sb.append(String.format(Locale.ROOT,
                                "  // %d redstone tick(s) of delay here (%d ms) - not reproduced%n",
                                g.delayTicks, g.delayTicks * 100));
                    }
                    sb.append(String.format(Locale.ROOT, "  bool %s = %s;%n",
                            names.get(id), expression(g, names)));
                }
            }
        }

        sb.append("}\n");
        return sb.toString();
    }

    private static void emitLatch(StringBuilder sb, LogicDiagram diagram,
                                  LogicDiagram.Gate g, Map<Integer, String> names) {
        String set = "false";
        String reset = "false";
        for (int i = 0; i < g.inputs.size(); i++) {
            String ref = names.get(g.inputs.get(i).gate());
            if ("S".equals(g.inputPins.get(i))) {
                set = ref;
            } else if ("R".equals(g.inputPins.get(i))) {
                reset = ref;
            }
        }
        String q = names.get(g.id) + "_q";
        sb.append("  // SR latch. Reset wins when both are asserted, matching a torch latch's\n");
        sb.append("  // behaviour of pulling both outputs low.\n");
        sb.append(String.format(Locale.ROOT, "  if (%s) { %s = false; } else if (%s) { %s = true; }%n",
                reset, q, set, q));
        sb.append(String.format(Locale.ROOT, "  bool %s = %s;%n", names.get(g.id), q));
    }

    private static String expression(LogicDiagram.Gate g, Map<Integer, String> names) {
        List<String> args = new ArrayList<>();
        for (LogicDiagram.Ref r : g.inputs) {
            args.add(names.get(r.gate()));
        }
        if (args.isEmpty()) {
            return "false";
        }
        return switch (g.type) {
            case BUFFER, DELAY -> args.get(0);
            case NOT -> "!" + args.get(0);
            case AND -> String.join(" && ", args);
            case OR -> String.join(" || ", args);
            case NAND -> "!(" + String.join(" && ", args) + ")";
            case NOR -> "!(" + String.join(" || ", args) + ")";
            case XOR -> String.join(" != ", args);
            case XNOR -> "(" + String.join(" == ", args) + ")";
            case INHIBIT -> args.get(0) + " && !" + args.get(1);
            default -> "/* " + (g.note == null ? "unmatched" : g.note) + " */ "
                    + String.join(" /* ? */ ", args);
        };
    }

    private static String identifier(String label) {
        StringBuilder sb = new StringBuilder();
        for (char c : label.toCharArray()) {
            sb.append(Character.isLetterOrDigit(c) ? Character.toLowerCase(c) : '_');
        }
        return sb.isEmpty() ? "x" : sb.toString();
    }
}
